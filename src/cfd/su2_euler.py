"""SU2 set-up for the V3 regime: steady 2-D compressible inviscid (Euler) flow (AeroForge-TRIAD, protocol v3).

Free stream along +x (angle of attack applied by rotating the geometry, as V1/V2), so SU2's LIFT/DRAG are CL/CD.
Numerics fixed by the local pilot of 2026-10-14 (docs/plan_v3_transonic_DRAFT.md): JST, implicit Euler,
3-level W-cycle multigrid, CFL 10, convergence on rms[rho]. Dimensional free stream (p 101325 Pa, T 288.15 K);
force coefficients are non-dimensional. Volume output includes Pressure_Coefficient and the conservative
variables, from which data.postprocess_euler builds the learning targets.
"""
from __future__ import annotations

from pathlib import Path

EULER_TEMPLATE = """\
% AeroForge-TRIAD V3 | steady 2D compressible Euler | generated by src/cfd/su2_euler.py
SOLVER= EULER
MATH_PROBLEM= DIRECT
RESTART_SOL= NO
MACH_NUMBER= {mach:.6f}
AOA= 0.0
SIDESLIP_ANGLE= 0.0
FREESTREAM_PRESSURE= 101325.0
FREESTREAM_TEMPERATURE= 288.15
REF_ORIGIN_MOMENT_X= 0.25
REF_ORIGIN_MOMENT_Y= 0.00
REF_ORIGIN_MOMENT_Z= 0.00
REF_LENGTH= 1.0
REF_AREA= 1.0
%
MARKER_EULER= ( airfoil )
MARKER_FAR= ( farfield )
MARKER_PLOTTING= ( airfoil )
MARKER_MONITORING= ( airfoil )
%
NUM_METHOD_GRAD= GREEN_GAUSS
CFL_NUMBER= {cfl}
CFL_ADAPT= NO
MGLEVEL= 3
MGCYCLE= W_CYCLE
MG_PRE_SMOOTH= ( 1, 2, 3, 3 )
MG_POST_SMOOTH= ( 0, 0, 0, 0 )
MG_CORRECTION_SMOOTH= ( 0, 0, 0, 0 )
MG_DAMP_RESTRICTION= 0.75
MG_DAMP_PROLONGATION= 0.75
ITER= {iters}
CONV_NUM_METHOD_FLOW= JST
JST_SENSOR_COEFF= ( 0.5, 0.02 )
TIME_DISCRE_FLOW= EULER_IMPLICIT
LINEAR_SOLVER= FGMRES
LINEAR_SOLVER_PREC= ILU
LINEAR_SOLVER_ERROR= 1E-6
LINEAR_SOLVER_ITER= 20
%
CONV_FIELD= RMS_DENSITY
CONV_RESIDUAL_MINVAL= {res_min}
CONV_STARTITER= 10
%
MESH_FILENAME= mesh.su2
MESH_FORMAT= SU2
TABULAR_FORMAT= CSV
CONV_FILENAME= history
RESTART_FILENAME= restart_flow.dat
VOLUME_FILENAME= flow
SURFACE_FILENAME= surface_flow
OUTPUT_FILES= (RESTART, SURFACE_PARAVIEW_ASCII, SURFACE_CSV)
VOLUME_OUTPUT= (COORDINATES, SOLUTION, PRIMITIVE)
OUTPUT_WRT_FREQ= {iters}
SCREEN_OUTPUT= (INNER_ITER, RMS_DENSITY, LIFT, DRAG)
SCREEN_WRT_FREQ_INNER= 100
HISTORY_OUTPUT= (ITER, RMS_RES, AERO_COEFF)
"""

RES_KEY = "rms[Rho]"            # history column of the primal convergence field
ADJ_CONV_FIELD = "RMS_ADJ_DENSITY"
ADJ_RES_KEY = "rms[A_Rho]"


def write_euler_config(case_dir: Path, mach: float, iters: int = 3000, cfl: float = 10.0,
                       res_min: float = -10.0) -> Path:
    cfg = Path(case_dir) / "config.cfg"
    cfg.write_text(EULER_TEMPLATE.format(mach=mach, cfl=cfl, iters=iters, res_min=res_min))
    return cfg
