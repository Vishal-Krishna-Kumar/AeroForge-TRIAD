def write_config(case_dir: Path, reynolds: float, iters: int = 4000, cfl: float = 50.0,
                 res_min: float = -9.0, conv: str = "residual", cauchy_eps: float = 1e-5) -> Path:
    """conv='residual': stop at rms[P] <= res_min (v1).
    conv='cauchy': stop when CL and CD have both settled (Cauchy series over 100 iterations,
    eps `cauchy_eps`; 1e-6 never triggered on the production mesh although CL had settled to
    1e-4, so 1e-5 is the default). The residual is still recorded and checked afterwards."""
    text = CONFIG_TEMPLATE.format(mu=1.0 / reynolds, iters=iters, cfl=cfl, res_min=res_min)
    if conv == "cauchy":
        text = re.sub(r"(?m)^CONV_FIELD= .*$", "CONV_FIELD= (LIFT, DRAG)", text)
        text += f"CONV_CAUCHY_ELEMS= 100\nCONV_CAUCHY_EPS= {cauchy_eps:g}\n"
    elif conv != "residual":
        raise ValueError(f"unknown conv mode {conv!r}")
    cfg = case_dir / "config.cfg"
    cfg.write_text(text)
    return cfg


def run_su2(case_dir: Path, su2_bin: str, threads: int = 2, timeout_s: int = 3600) -> dict:
    """Run SU2_CFD in case_dir; full log kept in solver.log."""
    t0 = time.time()
    with open(case_dir / "solver.log", "w") as log:
        proc = subprocess.run([str(Path(su2_bin).resolve()), "-t", str(threads), "config.cfg"], cwd=case_dir,
                              stdout=log, stderr=subprocess.STDOUT, timeout=timeout_s)
    return {"returncode": proc.returncode, "wall_s": round(time.time() - t0, 1)}


def read_history(case_dir: Path) -> dict:
    with open(case_dir / "history.csv") as fh:
        rows = list(csv.reader(fh))
    head = [h.strip().strip('"') for h in rows[0]]
    data = np.array([[float(v) for v in r] for r in rows[1:] if r], dtype=float)
    return {h: data[:, i] for i, h in enumerate(head)}


def integrate_surface(case_dir: Path) -> dict:
    """Independent force integration from surface_flow.vtk (Cp and Cf on wall line elements).

    For each wall segment: dF = (-Cp n + Cf) ds, with n the unit normal pointing out of the
    body (into the fluid). Orientation is fixed from the sign of each segment's normal relative
    to the body centroid, so the result does not depend on SU2's element ordering."""
    import meshio
    m = meshio.read(case_dir / "surface_flow.vtk")
    pts = m.points[:, :2]
    cp = np.asarray(m.point_data["Pressure_Coefficient"]).reshape(-1)
    cf = np.asarray(m.point_data["Skin_Friction_Coefficient"])[:, :2]
    lines = np.vstack([c.data for c in m.cells if c.type == "line"])
    a, b = pts[lines[:, 0]], pts[lines[:, 1]]
    t = b - a
    ds = np.hypot(t[:, 0], t[:, 1])
    n = np.column_stack([t[:, 1], -t[:, 0]]) / ds[:, None]
    mid = 0.5 * (a + b)
    centroid = pts.mean(axis=0)
    flip = np.sign(np.einsum("ij,ij->i", n, mid - centroid))
    flip[flip == 0] = 1.0
    n = n * flip[:, None]
    cpm = 0.5 * (cp[lines[:, 0]] + cp[lines[:, 1]])
    cfm = 0.5 * (cf[lines[:, 0]] + cf[lines[:, 1]])
    fp = np.sum((-cpm)[:, None] * n * ds[:, None], axis=0)
    fv = np.sum(cfm * ds[:, None], axis=0)
    return {"CD_pressure": float(fp[0]), "CD_viscous": float(fv[0]), "CD_total": float(fp[0] + fv[0]),
            "CL_pressure": float(fp[1]), "CL_viscous": float(fv[1]), "CL_total": float(fp[1] + fv[1]),
            "n_wall_segments": int(len(lines)), "normals_flipped": int((flip < 0).sum())}


def assess(case_dir: Path, res_min: float, window: int | None = 100) -> dict:
    """Convergence and sanity assessment of a finished steady run.

    The coefficient spreads are measured over the last `window` iterations (fixed, 100 by default,
    matching the 100-iteration Cauchy series). window=None reproduces the v1 rule (last 10 %)."""
    h = read_history(case_dir)
    keys = list(h.keys())
    rms_p = next(k for k in keys if "rms[P]" in k or "RMS_PRESSURE" in k)
    cl_key = next(k for k in keys if k in ("CL", "LIFT"))
    cd_key = next(k for k in keys if k in ("CD", "DRAG"))
    n = len(h[rms_p])
    tail = max(10, n // 10) if window is None else min(int(window), n)
    cl_tail, cd_tail = h[cl_key][-tail:], h[cd_key][-tail:]
    return {
        "iterations": int(n),
        "final_rms_pressure_log10": float(h[rms_p][-1]),
        "residual_drop_orders": float(h[rms_p][0] - h[rms_p][-1]),
        "reached_res_min": bool(h[rms_p][-1] <= res_min),
        "CL": float(h[cl_key][-1]),
        "CD": float(h[cd_key][-1]),
        "CL_tail_rel_spread": float(np.ptp(cl_tail) / max(abs(cl_tail.mean()), 1e-12)),
        "CD_tail_rel_spread": float(np.ptp(cd_tail) / max(abs(cd_tail.mean()), 1e-12)),
        "finite": bool(np.isfinite(h[cl_key][-1]) and np.isfinite(h[cd_key][-1])),
        "tail_window": int(tail),
        "history_columns": keys,
    }


def save_json(path: Path, obj: dict) -> None:
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(json.dumps(obj, indent=2, default=float))
    os.replace(tmp, path)


def continuation_config(text: str, chunk: int) -> str:
    """Config for continuing a steady run from its restart file for exactly `chunk` iterations.

    SU2's Cauchy test averages per-iteration relative changes; on the production mesh those carry
    ~1e-6 jitter, so a tight eps never fires while a loose eps (1e-5) stops before CL has settled
    to 1e-4 over 100 iterations. Continuation chunks with an unreachable residual target let our own
    100-iteration spread test decide instead."""
    rules = {"RESTART_SOL": "YES", "SOLUTION_FILENAME": "solution_flow.dat", "ITER": str(int(chunk)),
             "CONV_FIELD": "RMS_PRESSURE", "CONV_RESIDUAL_MINVAL": "-16", "OUTPUT_WRT_FREQ": str(int(chunk))}
    out, seen = [], set()
    for line in text.splitlines():
        key = line.split("=", 1)[0].strip() if "=" in line and not line.lstrip().startswith("%") else None
        if key in ("CONV_CAUCHY_ELEMS", "CONV_CAUCHY_EPS"):
            continue
        if key in rules:
            out.append(f"{key}= {rules[key]}")
            seen.add(key)
        else:
            out.append(line)
    out += [f"{k}= {v}" for k, v in rules.items() if k not in seen]
    return "\n".join(out) + "\n"


def append_history(case_dir: Path, seg_path: Path) -> int:
    """Append a continuation segment's history (seg_path) to history.csv, renumbering Inner_Iter
    so the combined history is one consistent record. Returns the combined row count."""
    with open(case_dir / "history.csv") as fh:
        base = [r for r in csv.reader(fh) if r]
    with open(seg_path) as fh:
        seg = [r for r in csv.reader(fh) if r]
    head = [h.strip().strip('"') for h in base[0]]
    if [h.strip().strip('"') for h in seg[0]] != head:
        raise ValueError("continuation history columns differ from the original run")
    col = head.index("Inner_Iter") if "Inner_Iter" in head else None
    start = len(base) - 1
    for i, r in enumerate(seg[1:]):
        if col is not None:
            r[col] = str(start + i)
        base.append(r)
    tmp = case_dir / "history.csv.tmp"
    with open(tmp, "w", newline="") as fh:
        csv.writer(fh).writerows(base)
    os.replace(tmp, case_dir / "history.csv")
    return len(base) - 1
