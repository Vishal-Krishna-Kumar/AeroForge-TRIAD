"""SU2 case setup, execution and post-processing (AeroForge-TRIAD).

Physics (ADR-001): steady, 2D, incompressible, laminar Navier-Stokes (SU2 INC_NAVIER_STOKES,
no turbulence model). Non-dimensional set-up: chord c = 1, rho = 1, U_inf = 1, mu = 1/Re.
The free stream is along +x; angle of attack is applied by rotating the geometry, so
SU2's force coefficients map directly: CL = CFy ("LIFT"), CD = CFx ("DRAG").
Force coefficients are also re-integrated independently from the ASCII surface VTK (Cp, Cf).
"""
